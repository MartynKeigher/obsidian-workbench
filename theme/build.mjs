// Joins theme/src into the root theme.css in SECTIONS order, under one banner
// per UI area, and copies the manifest next to it. No dependencies.
import { copyFile, readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const here = new URL('./', import.meta.url);
const root = new URL('../', import.meta.url);

export const SECTIONS = [
  ['fonts.css', 'Fonts'],
  ['tokens.css', 'Tokens'],
  ['obsidian-vars.css', 'Obsidian variables'],
  ['icons.css', 'Icons'],
  ['base.css', 'Base'],
  ['components/layout.css', 'Layout'],
  ['components/header.css', 'Header band and note tabs'],
  ['components/ribbon.css', 'Ribbon'],
  ['components/sidebars.css', 'Sidebars'],
  ['components/left-sidebar.css', 'Left sidebar'],
  ['components/right-sidebar.css', 'Right sidebar'],
  ['components/note-header.css', 'Main notes area · Note header'],
  ['components/typography.css', 'Main notes area · Typography'],
  ['components/properties.css', 'Main notes area · Properties'],
  ['components/tags-pills.css', 'Main notes area · Tags and pills'],
  ['components/tasks.css', 'Main notes area · Tasks'],
  ['components/callouts.css', 'Main notes area · Callouts'],
  ['components/code.css', 'Main notes area · Code blocks'],
  ['components/live-preview.css', 'Main notes area · Live Preview'],
  ['components/tables.css', 'Main notes area · Tables'],
  ['components/embeds.css', 'Main notes area · Embeds, footnotes and maths'],
  ['components/status-bar.css', 'Status bar'],
  ['components/buttons.css', 'Buttons'],
  ['components/canvas.css', 'Canvas'],
  ['components/prompts.css', 'Prompts and modals'],
  ['components/light-mode.css', 'Light mode'],
  ['components/mobile.css', 'Phones'],
];

export const SOURCES = SECTIONS.map(([file]) => file);

const banner = (title) => `/* ========================================\n   ${title.toUpperCase()}\n   ======================================== */\n\n`;

const HEADER = '/* Workbench for Obsidian · built from theme/src · do not edit this file */\n';

// Themes are a single file, so each url("../fonts/x.woff2") becomes a data URI.
async function inlineFonts(css) {
  const pattern = /url\("\.\.\/fonts\/([\w.-]+\.woff2)"\)/g;
  const names = [...new Set([...css.matchAll(pattern)].map((match) => match[1]))];
  const uris = new Map(
    await Promise.all(
      names.map(async (name) => {
        const font = await readFile(new URL(`fonts/${name}`, here));
        return [name, `url("data:font/woff2;base64,${font.toString('base64')}")`];
      }),
    ),
  );
  return css.replace(pattern, (_, name) => uris.get(name));
}

async function assertAllSourcesListed() {
  const files = await readdir(new URL('src/', here), { recursive: true });
  const unlisted = files
    .map((file) => file.replaceAll('\\', '/'))
    .filter((file) => file.endsWith('.css') && !SOURCES.includes(file));
  if (unlisted.length > 0) {
    throw new Error(`Add to SOURCES in theme/build.mjs: ${unlisted.join(', ')}`);
  }
}

export async function build() {
  await assertAllSourcesListed();
  const parts = await Promise.all(
    SECTIONS.map(async ([src, title]) => banner(title) + (await readFile(new URL(`src/${src}`, here), 'utf8'))),
  );
  const css = await inlineFonts(HEADER + parts.join('\n'));
  await writeFile(new URL('theme.css', root), css);
  await copyFile(new URL('manifest.json', here), new URL('manifest.json', root));
  return { css };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { css } = await build();
  console.log(`theme.css: ${css.length} bytes from ${SOURCES.length} sources`);
}
